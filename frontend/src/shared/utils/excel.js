// List of all fields with their key, label, and whether required
export const ALL_FIELDS_CONFIG = [
  ...CM_BASIC_FIELDS,
  ...CM_LEGAL_FIELDS,
  ...CM_ADDRESS_FIELDS,
  { key: "status", label: "Status" },
];

const REQUIRED_KEYS = ["companyName", "panNo", "gstin", "registeredOffice", "country", "state", "city"];

// Map header string (e.g. "Company Code", "Company Name * (Required)") to canonical field key
function normalizeHeader(h) {
  return String(h || "")
    .toLowerCase()
    .replace(/required|optional|auto-generated|autogenerated/g, "")
    .replace(/[^a-z0-9]/g, "");
}

const HEADER_MAP = {};
ALL_FIELDS_CONFIG.forEach((f) => {
  HEADER_MAP[normalizeHeader(f.key)] = f.key;
  HEADER_MAP[normalizeHeader(f.label)] = f.key;
});
// Additional alias mappings for common variations
HEADER_MAP["panno"] = "panNo";
HEADER_MAP["pan"] = "panNo";
HEADER_MAP["cinllpin"] = "cinLlpin";
HEADER_MAP["cin"] = "cinLlpin";
HEADER_MAP["importexportcodeiec"] = "iec";
HEADER_MAP["pincode"] = "pinCode";
HEADER_MAP["zip"] = "pinCode";
HEADER_MAP["zipcode"] = "pinCode";
HEADER_MAP["registeredoffice"] = "registeredOffice";
HEADER_MAP["factoryaddress"] = "factoryAddress";
HEADER_MAP["branchaddress"] = "branchAddress";
HEADER_MAP["businesstype"] = "businessType";
HEADER_MAP["companycode"] = "companyCode";
HEADER_MAP["companyname"] = "companyName";
HEADER_MAP["legalname"] = "legalName";
HEADER_MAP["shortname"] = "shortName";

// Helper to normalize field values for duplicate checking
const norm = (v) => (v === null || v === undefined ? "" : String(v).trim());

const ALL_RECORD_FIELDS = ALL_FIELDS_CONFIG.map((f) => f.key);

function isExactDuplicate(rec1, rec2) {
  return ALL_RECORD_FIELDS.every((k) => norm(rec1[k]) === norm(rec2[k]));
}

