// Parse Excel file, validate header & fields & duplicates against constraints
export function parseAndValidateExcel(file, existingRecords = []) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();

    reader.onload = (e) => {
      try {
        const data = new Uint8Array(e.target.result);
        const workbook = XLSX.read(data, { type: "array" });

        const firstSheetName = workbook.SheetNames[0];
        if (!firstSheetName) {
          return resolve({ valid: false, errors: ["Excel file contains no sheets."], records: [] });
        }

        const worksheet = workbook.Sheets[firstSheetName];
        const rawJson = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: "" });

        if (rawJson.length === 0) {
          return resolve({ valid: false, errors: ["Excel sheet is completely empty."], records: [] });
        }

        // Header row (Row 1)
        const headerRow = rawJson[0].map((h) => String(h).trim());
        const fieldMapping = {}; // colIndex -> canonical key

        headerRow.forEach((colName, idx) => {
          const normH = normalizeHeader(colName);
          if (HEADER_MAP[normH]) {
            fieldMapping[idx] = HEADER_MAP[normH];
          }
        });

        // Verify all REQUIRED columns are present in the Excel header
        const mappedKeys = new Set(Object.values(fieldMapping));
        const missingRequiredColumns = [];
        REQUIRED_KEYS.forEach((reqKey) => {
          if (!mappedKeys.has(reqKey)) {
            const config = ALL_FIELDS_CONFIG.find((f) => f.key === reqKey);
            missingRequiredColumns.push(config ? config.label : reqKey);
          }
        });

        if (missingRequiredColumns.length > 0) {
          return resolve({
            valid: false,
            errors: [
              `Missing required column(s) in Excel header: ${missingRequiredColumns.join(", ")}. Please include all required columns.`,
            ],
            records: [],
          });
        }

        const dataRows = rawJson.slice(1);
        if (dataRows.length === 0) {
          return resolve({ valid: false, errors: ["Excel sheet has headers but no data rows."], records: [] });
        }

        const parsedRecords = [];
        const errors = [];

        // Valid state list for state checking
        const stateConfig = ALL_FIELDS_CONFIG.find((f) => f.key === "state");
        const validStates = new Set((stateConfig?.options || []).map((s) => s.toLowerCase()));

        // Process and validate each data row
        dataRows.forEach((row, rowIdx) => {
          const rowNumber = rowIdx + 2; // Row 1 is header, data starts at Row 2

          // Check if row is completely blank
          const isBlankRow = row.every((cell) => cell === null || cell === undefined || String(cell).trim() === "");
          if (isBlankRow) return;

          const rec = { status: "Active", logo: "" };
          ALL_FIELDS_CONFIG.forEach((f) => {
            if (f.key !== "status" && f.key !== "logo") rec[f.key] = "";
          });

          // Populate mapped cells
          Object.keys(fieldMapping).forEach((colIdx) => {
            const key = fieldMapping[colIdx];
            const cellVal = row[colIdx];
            rec[key] = cellVal !== null && cellVal !== undefined ? String(cellVal).trim() : "";
          });

          // Standardize businessType default if empty
          if (!rec.businessType) rec.businessType = "Manufacturing";
          if (!rec.status) rec.status = "Active";

          // 1. Company Code (Auto-assigned if missing/empty)
          if (!rec.companyCode || !rec.companyCode.trim()) {
            rec.companyCode = getNextCompanyCode(existingRecords.concat(parsedRecords));
          }

          // Field validations per row
          const rowErrors = [];

          // 2. Company Name
          if (!rec.companyName) {
            rowErrors.push("Company Name is required");
          }

          // 3. PAN No.
          if (!rec.panNo) {
            rowErrors.push("PAN No. is required");
          } else if (!/^[A-Za-z]{5}[0-9]{4}[A-Za-z]{1}$/.test(rec.panNo)) {
            rowErrors.push(`PAN No. '${rec.panNo}' is invalid (must be 10 characters e.g. ABCDE1234F)`);
          }

          // 4. GSTIN
          if (!rec.gstin) {
            rowErrors.push("GSTIN is required");
          } else if (rec.gstin.length !== 15 || /^0+$/.test(rec.gstin)) {
            rowErrors.push(`GSTIN '${rec.gstin}' is invalid (must be 15 characters)`);
          }

          // 5. Registered Office
          if (!rec.registeredOffice) {
            rowErrors.push("Registered Office is required");
          }

          // 6. Country
          if (!rec.country) {
            rowErrors.push("Country is required");
          }

          // 7. City
          if (!rec.city) {
            rowErrors.push("City is required");
          }

          // 8. State
          if (!rec.state) {
            rowErrors.push("State / Province is required");
          } else if (rec.country.toLowerCase() === "india" && !validStates.has(rec.state.toLowerCase())) {
            rowErrors.push(`State '${rec.state}' is not a recognized Indian state/union territory`);
          }

          // 9. PIN / ZIP Code (6-digit check for India, flexible for international)
          if (rec.pinCode && rec.pinCode.trim()) {
            const isIndia = (rec.country || "").toLowerCase() === "india";
            if (isIndia && !/^[1-9][0-9]{5}$/.test(rec.pinCode.trim())) {
              rowErrors.push(`PIN Code '${rec.pinCode}' must be a valid 6-digit PIN for India`);
            }
          }

          if (rowErrors.length > 0) {
            errors.push(`Row ${rowNumber}: ${rowErrors.join("; ")}`);
          } else {
            parsedRecords.push({ ...rec, _excelRowNumber: rowNumber });
          }
        });

        if (errors.length > 0) {
          return resolve({ valid: false, errors, records: [] });
        }

        // Duplicate validations:
        // A) Check inside the uploaded Excel sheet for duplicate rows
        for (let i = 0; i < parsedRecords.length; i++) {
          for (let j = i + 1; j < parsedRecords.length; j++) {
            if (isExactDuplicate(parsedRecords[i], parsedRecords[j])) {
              errors.push(
                `Duplicate in Excel file: Row ${parsedRecords[i]._excelRowNumber} and Row ${parsedRecords[j]._excelRowNumber} have identical company details.`
              );
            }
          }
        }

        // B) Check against existing records in database / system
        parsedRecords.forEach((newRec) => {
          const match = existingRecords.find((existRec) => isExactDuplicate(existRec, newRec));
          if (match) {
            errors.push(
              `Row ${newRec._excelRowNumber} (${newRec.companyName} - ${newRec.companyCode}): Exactly identical record already exists in the system.`
            );
          }
        });

        if (errors.length > 0) {
          return resolve({ valid: false, errors, records: [] });
        }

        // Strip metadata helper key before returning
        const finalRecords = parsedRecords.map(({ _excelRowNumber, ...rest }) => rest);
        resolve({ valid: true, errors: [], records: finalRecords });
      } catch (err) {
        resolve({ valid: false, errors: [`Failed to parse Excel file: ${err.message}`], records: [] });
      }
    };

    reader.onerror = () => {
      resolve({ valid: false, errors: ["Failed to read file from disk."], records: [] });
    };

    reader.readAsArrayBuffer(file);
  });
}

// Export any array of company records to an .xlsx file download
export function exportRecordsToExcel(recordsList, filename = "Company_Master_Records.xlsx") {
  if (!recordsList || recordsList.length === 0) return;

  const formattedRows = recordsList.map((r) => {
    const row = {};
    ALL_FIELDS_CONFIG.forEach((f) => {
      row[f.label] = r[f.key] || "";
    });
    return row;
  });

  const worksheet = XLSX.utils.json_to_sheet(formattedRows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "Company Records");

  const colWidths = Object.keys(formattedRows[0]).map((key) => ({
    wch: Math.max(key.length + 3, 16),
  }));
  worksheet["!cols"] = colWidths;

  XLSX.writeFile(workbook, filename);
}

