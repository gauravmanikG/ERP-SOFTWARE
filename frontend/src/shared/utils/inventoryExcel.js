const REQUIRED_HEADERS = ["type", "fromDept", "itemCode", "quantity"];

// Normalize header text for flexible matching:
// 1. Removes text in parentheses (e.g. "(Required: ISSUE / RECEIPT / REVERSE)", "(Optional)")
// 2. Removes asterisks, punctuation, spaces, and lowers case
function normalizeHeader(h) {
  return String(h || "")
    .replace(/\([^)]*\)/g, "") // Strip anything inside parentheses
    .replace(/required|optional|auto-generated|autogenerated/gi, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

