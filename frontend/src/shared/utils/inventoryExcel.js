/**
 * Parse Excel / CSV file, validate required headers & rows against master items, departments, and balances
 */
export function parseAndValidateInventoryExcel(file, { departments = [], masterItems = [], getDeptBalance = () => 0 }) {
  return new Promise((resolve) => {
    const reader = new FileReader();

    reader.onload = (e) => {
      try {
        const data = new Uint8Array(e.target.result);
        const workbook = XLSX.read(data, { type: "array" });

        if (!workbook.SheetNames || workbook.SheetNames.length === 0) {
          return resolve({ valid: false, errors: ["Excel file contains no sheets."], records: [] });
        }

        // Intelligently select the sheet containing transaction data (or fallback to first sheet)
        const targetSheetName =
          workbook.SheetNames.find((n) => /trans|template|entry|sheet1|data/i.test(n)) ||
          workbook.SheetNames[0];

        const worksheet = workbook.Sheets[targetSheetName];
        const rawJson = XLSX.utils.sheet_to_json(worksheet, { header: 1, defval: "" });

        if (rawJson.length === 0) {
          return resolve({ valid: false, errors: ["Excel sheet is completely empty."], records: [] });
        }

        // Header row (Row 1)
        const headerRow = rawJson[0].map((h) => String(h).trim());
        const fieldMapping = {}; // colIndex -> canonical key

        headerRow.forEach((colName, idx) => {
          const normH = normalizeHeader(colName);
          if (HEADER_MAP[normH]) {
            fieldMapping[idx] = HEADER_MAP[normH];
          }
        });

        // Verify all REQUIRED columns are present in the Excel header
        const mappedKeys = new Set(Object.values(fieldMapping));
        const missingRequiredColumns = [];
        REQUIRED_HEADERS.forEach((reqKey) => {
          if (!mappedKeys.has(reqKey)) {
            const config = INVENTORY_EXCEL_FIELDS.find((f) => f.key === reqKey);
            missingRequiredColumns.push(config ? config.label : reqKey);
          }
        });

        if (missingRequiredColumns.length > 0) {
          return resolve({
            valid: false,
            errors: [
              `Missing required column(s) in Excel header: ${missingRequiredColumns.join(", ")}. Please ensure columns for 'Type', 'From Dept', 'Item Code', and 'Quantity' exist.`,
            ],
            records: [],
          });
        }

        const dataRows = rawJson.slice(1);
        if (dataRows.length === 0) {
          return resolve({ valid: false, errors: ["Excel sheet has headers but no transaction rows."], records: [] });
        }

        // Fallback lookup maps for departments and master items if lists are loading
        const effectiveDepts = departments.length > 0 ? departments : [
          { id: 4, name: "Stores" },
          { id: 1, name: "Production" },
          { id: 2, name: "Maintenance" },
          { id: 3, name: "Quality Control" },
          { id: 5, name: "Administration" }
        ];

        const effectiveMasters = masterItems.length > 0 ? masterItems : [
          { id: 1, code: "MAT-001", description: "Steel Sheet", category: "Raw Material", unitOfMeasurement: "KG", currentBalance: 5000 },
          { id: 2, code: "MAT-002", description: "Stainless Steel Rod", category: "Raw Material", unitOfMeasurement: "KG", currentBalance: 2500 },
          { id: 3, code: "MAT-003", description: "Bearing 6205", category: "Spare Parts", unitOfMeasurement: "PCS", currentBalance: 150 },
          { id: 4, code: "MAT-004", description: "Lubricating Oil", category: "Consumables", unitOfMeasurement: "LTR", currentBalance: 500 },
          { id: 5, code: "MAT-005", description: "Welding Electrode", category: "Consumables", unitOfMeasurement: "KG", currentBalance: 300 }
        ];

        const deptMap = {};
        effectiveDepts.forEach((d) => {
          deptMap[d.name.trim().toLowerCase()] = d;
          deptMap[String(d.id)] = d;
        });

        const masterMap = {};
        effectiveMasters.forEach((m) => {
          masterMap[m.code.trim().toUpperCase()] = m;
          masterMap[String(m.id)] = m;
        });

        const parsedRecords = [];
        const errors = [];

        // Validate each data row
        dataRows.forEach((row, rowIdx) => {
          const rowNumber = rowIdx + 2; // Data starts at Row 2

          // Check if row is completely blank
          const isBlankRow = row.every((cell) => cell === null || cell === undefined || String(cell).trim() === "");
          if (isBlankRow) return;

          const rec = {
            rowNumber,
            slipNumber: "",
            type: "ISSUE",
            fromDept: "",
            toDept: "",
            itemCode: "",
            description: "",
            category: "",
            quantity: "",
            timestamp: "",
            remarks: "",
          };

          // Populate mapped cells
          Object.keys(fieldMapping).forEach((colIdx) => {
            const key = fieldMapping[colIdx];
            const cellVal = row[colIdx];
            rec[key] = cellVal !== null && cellVal !== undefined ? String(cellVal).trim() : "";
          });

          const rowErrors = [];

          // 1. Validate Transaction Type
          const upperType = (rec.type || "").toUpperCase().trim();
          if (!upperType) {
            rowErrors.push("Transaction Type is required (ISSUE, RECEIPT, or REVERSE)");
          } else if (!["ISSUE", "RECEIPT", "REVERSE"].includes(upperType)) {
            rowErrors.push(`Invalid Transaction Type '${rec.type}'. Must be ISSUE, RECEIPT, or REVERSE`);
          } else {
            rec.type = upperType;
          }

          // 2. Validate From Department
          if (!rec.fromDept) {
            rowErrors.push("From Dept is required");
          } else {
            const cleanFromDept = rec.fromDept.toLowerCase().trim();
            const matchedFromDept = deptMap[cleanFromDept];
            if (!matchedFromDept) {
              rowErrors.push(`From Dept '${rec.fromDept}' not found in departments list`);
            } else {
              rec.fromDepartmentId = matchedFromDept.id;
              rec.fromDepartmentName = matchedFromDept.name;
            }
          }

          // 3. Validate To Department (optional)
          if (rec.toDept && rec.toDept.trim()) {
            const cleanToDept = rec.toDept.toLowerCase().trim();
            const matchedToDept = deptMap[cleanToDept];
            if (!matchedToDept) {
              rowErrors.push(`To Dept '${rec.toDept}' not found in departments list`);
            } else {
              rec.toDepartmentId = matchedToDept.id;
              rec.toDepartmentName = matchedToDept.name;
            }
          } else {
            rec.toDepartmentId = null;
            rec.toDepartmentName = "";
          }

          // 4. Validate Item Code
          let matchedMaster = null;
          if (!rec.itemCode) {
            rowErrors.push("Item Code is required");
          } else {
            const cleanCode = rec.itemCode.toUpperCase().trim();
            matchedMaster = masterMap[cleanCode];
            if (!matchedMaster) {
              rowErrors.push(`Item Code '${rec.itemCode}' not found in Material Master`);
            } else {
              rec.masterId = matchedMaster.id;
              rec.masterCode = matchedMaster.code;
              rec.masterDescription = matchedMaster.description;
              rec.unitOfMeasurement = matchedMaster.unitOfMeasurement;
              if (!rec.description) rec.description = matchedMaster.description;
              if (!rec.category) rec.category = matchedMaster.category || "General";
            }
          }

          // 5. Populate Category
          if (!rec.category && matchedMaster) {
            rec.category = matchedMaster.category || "General";
          }

          // 6. Validate Quantity
          const numQty = Number(rec.quantity);
          if (!rec.quantity || isNaN(numQty) || numQty <= 0) {
            rowErrors.push(`Invalid Quantity '${rec.quantity}' (must be a positive number greater than 0)`);
          } else {
            rec.quantity = numQty;
          }

          // 7. Stock Balance Check for ISSUE transactions
          if (rec.type === "ISSUE" && matchedMaster && rec.fromDepartmentId && !isNaN(numQty) && numQty > 0) {
            const currentDeptBalance = Number(getDeptBalance(matchedMaster.id, rec.fromDepartmentId)) || 0;
            // Only alert if balance tracking is loaded and balance is strictly 0 or less than quantity
            if (currentDeptBalance > 0 && numQty > currentDeptBalance) {
              rowErrors.push(
                `Insufficient stock for '${matchedMaster.code}' in ${rec.fromDepartmentName}: requested ${numQty}, available closing balance is ${currentDeptBalance}`
              );
            }
          }

          if (rowErrors.length > 0) {
            errors.push(`Row ${rowNumber}: ${rowErrors.join(" | ")}`);
            rec._errors = rowErrors;
          } else {
            rec._errors = [];
          }

          parsedRecords.push(rec);
        });

        if (errors.length > 0) {
          return resolve({
            valid: false,
            errors,
            records: parsedRecords,
            validCount: parsedRecords.filter((r) => r._errors.length === 0).length,
            errorCount: errors.length,
          });
        }

        resolve({
          valid: true,
          errors: [],
          records: parsedRecords,
          validCount: parsedRecords.length,
          errorCount: 0,
        });
      } catch (err) {
        resolve({ valid: false, errors: [`Failed to parse Excel file: ${err.message}`], records: [] });
      }
    };

    reader.onerror = () => {
      resolve({ valid: false, errors: ["Failed to read file from disk."], records: [] });
    };

    reader.readAsArrayBuffer(file);
  });
}

/**
 * Export array of transactions to an .xlsx file download
 */
export function exportTransactionsToExcel(transactionsList = [], filename = "Inventory_Transactions_History.xlsx") {
  if (!transactionsList || transactionsList.length === 0) return;

  const formattedRows = transactionsList.map((tx) => ({
    "Transaction No.": tx.transactionNumber || tx.slipNumber || "-",
    "Slip No.": tx.slipNumber || "-",
    "Type": tx.transactionType || "-",
    "From Dept": tx.fromDepartmentName || "-",
    "To Dept": tx.toDepartmentName || "-",
    "Item Code": tx.masterCode || "-",
    "Description": tx.masterDescription || "-",
    "Category": tx.category || "-",
    "Quantity": tx.quantity || 0,
    "Timestamp": tx.transactionDate ? new Date(tx.transactionDate).toLocaleString("en-IN") : "-",
    "Remarks": tx.remarks || "",
  }));

  const worksheet = XLSX.utils.json_to_sheet(formattedRows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "Transaction History");

  const colWidths = Object.keys(formattedRows[0]).map((key) => ({
    wch: Math.max(key.length + 3, 16),
  }));
  worksheet["!cols"] = colWidths;

  XLSX.writeFile(workbook, filename);
}
