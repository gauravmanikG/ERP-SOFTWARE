package com.silvermuller.seals.modules.crm.controller;

import com.silvermuller.seals.modules.crm.model.CustomerMaster;
import com.silvermuller.seals.modules.crm.repository.CustomerMasterRepository;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@RestController
@RequestMapping({"/api/crm/customers", "/api/customers"})
public class CustomerMasterController {

    private final CustomerMasterRepository customerRepository;

    public CustomerMasterController(CustomerMasterRepository customerRepository) {
        this.customerRepository = customerRepository;
    }

    @GetMapping("/next-code")
    public ResponseEntity<Map<String, String>> getNextCustomerCode() {
        return ResponseEntity.ok(Map.of("nextCode", calculateNextCustomerCode()));
    }

    public synchronized String calculateNextCustomerCode() {
        List<CustomerMaster> all = customerRepository.findAll();
        int maxNum = 0;
        Pattern pattern = Pattern.compile("(?i)CUST-(\\d+)");
        for (CustomerMaster c : all) {
            String code = c.getCustomerCode();
            if (code != null) {
                Matcher m = pattern.matcher(code.trim());
                if (m.find()) {
                    try {
                        int val = Integer.parseInt(m.group(1));
                        if (val > maxNum) {
                            maxNum = val;
                        }
                    } catch (NumberFormatException ignored) {}
                }
            }
        }
        return String.format("CUST-%05d", maxNum + 1);
    }

    @GetMapping
    public ResponseEntity<List<CustomerMaster>> getAllCustomers(
            @RequestParam(required = false) String search,
            @RequestParam(required = false) String state,
            @RequestParam(required = false) String gstType) {

        if (search != null && !search.trim().isEmpty()) {
            return ResponseEntity.ok(customerRepository.searchCustomers(search.trim()));
        }
        if (state != null && !state.trim().isEmpty()) {
            return ResponseEntity.ok(customerRepository.findByStateIgnoreCase(state.trim()));
        }
        if (gstType != null && !gstType.trim().isEmpty()) {
            return ResponseEntity.ok(customerRepository.findByGstRegistrationTypeIgnoreCase(gstType.trim()));
        }
        return ResponseEntity.ok(customerRepository.findAllByOrderByIdAsc());
    }

    @GetMapping("/{id}")
    public ResponseEntity<CustomerMaster> getById(@PathVariable Long id) {
        return customerRepository.findById(id)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @GetMapping("/code/{code}")
    public ResponseEntity<CustomerMaster> getByCode(@PathVariable String code) {
        return customerRepository.findByCustomerCode(code)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @PostMapping
    public ResponseEntity<?> createCustomer(@RequestBody CustomerMaster customer) {
        if (customer.getCustomerName() == null || customer.getCustomerName().trim().isEmpty()) {
            return ResponseEntity.badRequest().body(Map.of("error", "Customer name is required"));
        }

        // Assign uneditable, unique, autogenerated code which is next value of maximum number assigned till yet
        String nextCode = calculateNextCustomerCode();
        customer.setCustomerCode(nextCode);
        if (customer.getCustomerId() == null || customer.getCustomerId().trim().isEmpty()) {
            customer.setCustomerId(nextCode);
        }

        // Auto-derive PAN if GSTIN provided and PAN not set
        if ((customer.getPan() == null || customer.getPan().isBlank()) && customer.getGstin() != null) {
            String gstin = customer.getGstin().trim();
            if (gstin.length() >= 15 && Character.isDigit(gstin.charAt(0)) && Character.isDigit(gstin.charAt(1))) {
                customer.setPan(gstin.substring(2, 12));
                if (customer.getStateCode() == null || customer.getStateCode().isBlank()) {
                    customer.setStateCode(gstin.substring(0, 2));
                }
            }
        }

        // Sync classification & market segmentation
        if (customer.getMarketType() != null && (customer.getDomesticExport() == null || customer.getDomesticExport().isBlank())) {
            customer.setDomesticExport(customer.getMarketType());
        } else if (customer.getDomesticExport() != null && (customer.getMarketType() == null || customer.getMarketType().isBlank())) {
            customer.setMarketType(customer.getDomesticExport());
        }

        if (customer.getCustomerCategory() != null && (customer.getCustomerType() == null || customer.getCustomerType().isBlank())) {
            customer.setCustomerType(customer.getCustomerCategory());
        } else if (customer.getCustomerType() != null && (customer.getCustomerCategory() == null || customer.getCustomerCategory().isBlank())) {
            customer.setCustomerCategory(customer.getCustomerType());
        }

        CustomerMaster saved = customerRepository.save(customer);
        return ResponseEntity.status(HttpStatus.CREATED).body(saved);
    }

    @PutMapping("/{id}")
    public ResponseEntity<?> updateCustomer(@PathVariable Long id, @RequestBody CustomerMaster input) {
        Optional<CustomerMaster> opt = customerRepository.findById(id);
        if (opt.isEmpty()) {
            return ResponseEntity.notFound().build();
        }
        CustomerMaster c = opt.get();
        if (input.getCustomerName() != null) c.setCustomerName(input.getCustomerName());
        if (input.getCustomerCode() != null) c.setCustomerCode(input.getCustomerCode());
        if (input.getCustomerAlias() != null) c.setCustomerAlias(input.getCustomerAlias());
        if (input.getCompanyId() != null) c.setCompanyId(input.getCompanyId());
        if (input.getCustomerType() != null) c.setCustomerType(input.getCustomerType());
        if (input.getCustomerCategory() != null) c.setCustomerCategory(input.getCustomerCategory());
        if (input.getCustomerCategory() != null && input.getCustomerType() == null) c.setCustomerType(input.getCustomerCategory());
        if (input.getCustomerType() != null && input.getCustomerCategory() == null) c.setCustomerCategory(input.getCustomerType());

        if (input.getDomesticExport() != null) c.setDomesticExport(input.getDomesticExport());
        if (input.getMarketType() != null) c.setMarketType(input.getMarketType());
        if (input.getMarketType() != null && input.getDomesticExport() == null) c.setDomesticExport(input.getMarketType());
        if (input.getDomesticExport() != null && input.getMarketType() == null) c.setMarketType(input.getDomesticExport());

        if (input.getCustomerGroup() != null) c.setCustomerGroup(input.getCustomerGroup());
        if (input.getGstin() != null) c.setGstin(input.getGstin());
        if (input.getPan() != null) c.setPan(input.getPan());
        if (input.getUdyamNo() != null) c.setUdyamNo(input.getUdyamNo());
        if (input.getMsmeCategory() != null) c.setMsmeCategory(input.getMsmeCategory());
        if (input.getGstRegistrationType() != null) c.setGstRegistrationType(input.getGstRegistrationType());
        if (input.getCheckByAccounts() != null) c.setCheckByAccounts(input.getCheckByAccounts());
        if (input.getCheckBySales() != null) c.setCheckBySales(input.getCheckBySales());
        if (input.getBillingSource() != null) c.setBillingSource(input.getBillingSource());
        if (input.getSupplierCodeSms() != null) c.setSupplierCodeSms(input.getSupplierCodeSms());
        if (input.getContactPerson() != null) c.setContactPerson(input.getContactPerson());
        if (input.getSalesPerson() != null) c.setSalesPerson(input.getSalesPerson());
        if (input.getPhone() != null) c.setPhone(input.getPhone());
        if (input.getSalesContact() != null) c.setSalesContact(input.getSalesContact());
        if (input.getEmail() != null) c.setEmail(input.getEmail());
        if (input.getSalesEmail() != null) c.setSalesEmail(input.getSalesEmail());
        if (input.getModeOfPaymentReminder() != null) c.setModeOfPaymentReminder(input.getModeOfPaymentReminder());
        if (input.getAccountsContactDetails() != null) c.setAccountsContactDetails(input.getAccountsContactDetails());
        if (input.getPaymentTermsId() != null) c.setPaymentTermsId(input.getPaymentTermsId());
        if (input.getCreditDays() != null) c.setCreditDays(input.getCreditDays());
        if (input.getCreditLimit() != null) c.setCreditLimit(input.getCreditLimit());
        if (input.getCurrency() != null) c.setCurrency(input.getCurrency());
        if (input.getScm() != null) c.setScm(input.getScm());
        if (input.getStatus() != null) c.setStatus(input.getStatus());
        if (input.getBillToAddress() != null) c.setBillToAddress(input.getBillToAddress());
        if (input.getShipToAddress() != null) c.setShipToAddress(input.getShipToAddress());
        if (input.getCustomerAddress() != null) c.setCustomerAddress(input.getCustomerAddress());
        if (input.getAddress() != null) c.setAddress(input.getAddress());
        if (input.getCity() != null) c.setCity(input.getCity());
        if (input.getState() != null) c.setState(input.getState());
        if (input.getStateCode() != null) c.setStateCode(input.getStateCode());
        if (input.getCountry() != null) c.setCountry(input.getCountry());
        if (input.getPincode() != null) c.setPincode(input.getPincode());
        if (input.getUpdatedBy() != null) c.setUpdatedBy(input.getUpdatedBy());

        return ResponseEntity.ok(customerRepository.save(c));
    }

    @DeleteMapping("/{id}")
    public ResponseEntity<Map<String, String>> deleteCustomer(@PathVariable Long id) {
        if (!customerRepository.existsById(id)) {
            return ResponseEntity.notFound().build();
        }
        customerRepository.deleteById(id);
        return ResponseEntity.ok(Map.of("message", "Customer deleted successfully"));
    }
}
